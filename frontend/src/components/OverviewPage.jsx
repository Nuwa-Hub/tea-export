import { fetchDashboard } from "../api";
import { useApi } from "../hooks";
import ForecastChart from "./ForecastChart";
import NeedsTraining from "./NeedsTraining";
import ReadinessCard from "./ReadinessCard";

function StatCard({ label, value, sub, color }) {
  return (
    <div className="stat-card">
      <div className="stat-value" style={color ? { color } : undefined}>{value}</div>
      <div className="stat-label">{label}</div>
      {sub && <div className="stat-sub">{sub}</div>}
    </div>
  );
}

const RISK_COLOR = { Low: "#2e7d32", Moderate: "#ed9b00", High: "#c0392b" };

export default function OverviewPage({ horizon, goTrain }) {
  const { data, loading, error, needsTraining } = useApi(() => fetchDashboard(horizon), [horizon]);

  if (needsTraining) return <NeedsTraining goTrain={goTrain} />;
  if (loading) return <p className="muted">Loading platform overview…</p>;
  if (error) return <p className="error">⚠ {error}</p>;
  if (!data) return null;

  const rec = data.recommendation || {};
  const risk = data.storage_risk || {};
  const priceFc = data.forecasts.auction_price_usd;
  const lastPrice = data.history[data.history.length - 1].auction_price_usd;
  const priceTrend = priceFc.forecast.length
    ? (((priceFc.forecast.at(-1) - lastPrice) / lastPrice) * 100).toFixed(1)
    : "0";

  return (
    <div className="page">
      <div className="stat-row">
        <StatCard label="Export Readiness Index" value={`${data.readiness.eri}`}
          sub={data.readiness.status} color="#2e7d32" />
        <StatCard label="Top opportunity" value={rec.country || "—"}
          sub={`suitability ${rec.suitability ?? "—"}/100`} />
        <StatCard label="Price outlook" value={`${priceTrend > 0 ? "+" : ""}${priceTrend}%`}
          sub={`USD/kg over ${horizon}m (LSTM)`} color={priceTrend >= 0 ? "#2e7d32" : "#c0392b"} />
        <StatCard label="Storage risk" value={risk.level || "—"}
          sub={`index ${risk.forecast_avg ?? "—"}/100`} color={RISK_COLOR[risk.level]} />
      </div>

      <ReadinessCard readiness={data.readiness} />

      {data.advisor && (
        <div className="card advisor-mini">
          <h3>🧭 AI advisor</h3>
          <p className="advisor-text">{data.advisor.narrative}</p>
          <p className="hint">
            {data.advisor.generator === "llm" ? "Generated by Claude" : "Generated offline (template + RAG)"} ·
            sources: {data.advisor.citations.map((c) => c.source).join(", ") || "—"}
          </p>
        </div>
      )}

      <div className="grid">
        <ForecastChart title="Auction price (USD/kg)" history={data.history} field="auction_price_usd"
          futureDates={data.future_dates} lstm={priceFc.forecast} color="#2e7d32" />
        <ForecastChart title="Export volume (kg)" history={data.history} field="export_volume_kg"
          futureDates={data.future_dates} lstm={data.forecasts.export_volume_kg.forecast} color="#1565c0" />
      </div>
    </div>
  );
}
